#pragma once
#include <Arduino.h>

// Namespace Seai agrupa as métricas de erro usadas para avaliar as previsões do modelo....
namespace Seai {
// Classe que calcula métricas de erro para comparar previsões com valores esperados....
class Perdas {
public:
    // Calcula o erro quadrático médio a partir da soma dos erros e da quantidade de valores avaliados....
    // totalAmostras menor ou igual a zero devolve zero para evitar divisão inválida....
    float calcularMSE(float somaErrosQuadrados, int totalAmostras) {
        // Evita divisão por zero quando não há amostras para avaliar....
        if (totalAmostras <= 0) return 0.0f;
        // Converte o total para float para que a divisão preserve a parte fracionária da perda....
        return somaErrosQuadrados / (float)totalAmostras;
    }
};
}