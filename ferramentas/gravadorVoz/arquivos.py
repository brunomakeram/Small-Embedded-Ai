# Operações locais sobre os arquivos WAV produzidos pelo gravador de voz...
# A pasta base e o estado compartilhado vêm de config; os nomes usam palavra e sequência numérica...
# As funções retornam contagens ou caminhos e deixam falhas de disco visíveis para quem as chamou...

from config import PASTA_BASE, estado


# Conta recursivamente os arquivos WAV da pasta base, incluindo as subpastas por palavra...
# Devolve zero quando a pasta de gravações ainda não foi criada...
def contar_gravacoes():
    # Se a pasta ainda não existe, não tem nenhuma gravação...
    if not PASTA_BASE.exists():
        return 0
    return len(list(PASTA_BASE.rglob("*.wav")))


# Conta os arquivos WAV por palavra e devolve um dicionário como {"ligar": 4, "desligar": 2}...
# O rótulo é extraído do nome antes do último sublinhado, removendo o sufixo numérico da amostra...
def contar_por_palavra():
    contagem = {}
    if PASTA_BASE.exists():
        for arquivo in PASTA_BASE.rglob("*.wav"):
            # Tudo antes do último underline é a palavra...
            palavra = arquivo.stem.rsplit("_", 1)[0]
            contagem[palavra] = contagem.get(palavra, 0) + 1
    return contagem


# Salva os bytes WAV recebidos da placa na pasta correspondente ao modo selecionado...
# dados deve conter um WAV completo; o nome recebe o rótulo atual e o próximo número de sequência...
# Devolve o caminho gravado para que a interface possa reproduzir, manter ou excluir a amostra...
def salvar_wav(dados):
    palavra = estado["palavra"]
    # Pasta única ou subpasta com o nome da palavra...
    pasta = PASTA_BASE if estado["modo_pasta"] == 1 else PASTA_BASE / palavra
    pasta.mkdir(parents=True, exist_ok=True)
    # O número vem da contagem de arquivos, por isso só é seguro excluir a última gravação...
    # Se apagar uma do meio, a próxima sobrescreve outra que já existe...
    numero = len(list(pasta.glob(f"{palavra}_*.wav"))) + 1
    caminho = pasta / f"{palavra}_{numero:03d}.wav"
    # Os bytes já são um WAV completo, só grava...
    caminho.write_bytes(dados)
    return caminho


# Remove do disco o caminho da amostra que acabou de ser gravada e confirmada pelo usuário...
# Erros de remoção são propagados para não informar sucesso quando o arquivo permanece no disco...
def excluir_wav(caminho):
    caminho.unlink()
